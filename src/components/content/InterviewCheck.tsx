import { useEffect, useState, type ReactNode } from 'react';

/**
 * Self-checking interview questions for the interview-prep banks.
 *
 *   <Choice id q options answer>worked answer</Choice>   pick one; every option explains itself
 *   <Calc id q answer unit tolerance>worked answer</Calc>  a number, checked within a tolerance
 *   <BankScore />                                            "12 of 25 right first time" for the page
 *
 * The worked answer (children) unlocks after a correct attempt or "Show
 * the answer", so the question gets a real try first. Results live in
 * localStorage only. The banks are generated by scripts/interview/
 * build_banks.py, which computes every Calc answer from its formula.
 */

const STORAGE_KEY = 'nm-interview-checks:v1';
const EVENT = 'nm-interview-check';

interface Stored {
  firstTry: boolean;
  solved: boolean;
}

function readAll(): Record<string, Stored> {
  try {
    return JSON.parse(window.localStorage.getItem(STORAGE_KEY) ?? '{}');
  } catch {
    return {};
  }
}

function record(id: string, correct: boolean) {
  try {
    const all = readAll();
    const prev = all[id];
    all[id] = { firstTry: prev ? prev.firstTry : correct, solved: (prev?.solved ?? false) || correct };
    window.localStorage.setItem(STORAGE_KEY, JSON.stringify(all));
  } catch {
    // Storage blocked: the question still works, it just isn't remembered.
  }
  window.dispatchEvent(new Event(EVENT));
}

const registered = new Set<string>();

function useRegister(id: string) {
  useEffect(() => {
    registered.add(id);
    window.dispatchEvent(new Event(EVENT));
    return () => {
      registered.delete(id);
    };
  }, [id]);
}

/** `inline code` in question and option text, nothing else. */
function Inline({ text }: { text: string }) {
  const parts = text.split(/(`[^`]+`)/g);
  return (
    <>
      {parts.map((part, i) =>
        part.startsWith('`') && part.endsWith('`') ? <code key={i}>{part.slice(1, -1)}</code> : <span key={i}>{part}</span>,
      )}
    </>
  );
}

const boxStyle = {
  margin: '1.25rem 0',
  padding: '1rem 1.1rem',
  border: '1px solid var(--nm-border)',
  borderRadius: 10,
  background: 'var(--nm-surface)',
} as const;

function Worked({ children }: { children: ReactNode }) {
  return <div style={{ marginTop: '0.9rem', paddingTop: '0.75rem', borderTop: '1px solid var(--nm-border)' }}>{children}</div>;
}

function Verdict({ correct, text }: { correct: boolean; text: ReactNode }) {
  return (
    <p role="status" style={{ margin: '0.7rem 0 0', color: correct ? 'var(--nm-accent-primary)' : 'var(--nm-accent-danger)', fontWeight: 600 }}>
      {correct ? 'Right. ' : 'Not quite. '}
      <span style={{ fontWeight: 400, color: 'var(--nm-text-secondary)' }}>{text}</span>
    </p>
  );
}

export interface ChoiceOption {
  text: string;
  /** Why this option is right or wrong, shown once it's picked. */
  why: string;
}

export function Choice({ id, q, options, answer, children }: { id: string; q: string; options: ChoiceOption[]; answer: number; children: ReactNode }) {
  useRegister(id);
  const [picked, setPicked] = useState<number | null>(null);
  const [revealed, setRevealed] = useState(false);
  const solved = picked === answer;

  function pick(i: number) {
    if (solved) return;
    setPicked(i);
    record(id, i === answer);
  }

  return (
    <div style={boxStyle} data-check-id={id}>
      <p style={{ margin: '0 0 0.75rem', fontWeight: 600, color: 'var(--nm-text-primary)' }}>
        <Inline text={q} />
      </p>
      <div role="radiogroup" style={{ display: 'grid', gap: '0.45rem' }}>
        {options.map((option, i) => {
          const isPicked = picked === i;
          const border = isPicked ? (i === answer ? 'var(--nm-accent-primary)' : 'var(--nm-accent-danger)') : 'var(--nm-border)';
          return (
            <button
              key={i}
              type="button"
              role="radio"
              aria-checked={isPicked}
              onClick={() => pick(i)}
              disabled={solved && !isPicked}
              style={{
                textAlign: 'left',
                padding: '0.55rem 0.75rem',
                borderRadius: 8,
                border: `1.5px solid ${border}`,
                background: 'var(--nm-bg)',
                color: 'var(--nm-text-primary)',
                cursor: solved ? 'default' : 'pointer',
                font: 'inherit',
                fontSize: '0.95rem',
                opacity: solved && !isPicked ? 0.6 : 1,
              }}
            >
              <Inline text={option.text} />
            </button>
          );
        })}
      </div>
      {picked !== null && <Verdict correct={solved} text={<Inline text={options[picked].why} />} />}
      {!solved && !revealed && (
        <button type="button" onClick={() => setRevealed(true)} style={linkButton}>
          Show the answer
        </button>
      )}
      {(solved || revealed) && <Worked>{children}</Worked>}
    </div>
  );
}

const linkButton = {
  marginTop: '0.7rem',
  padding: 0,
  border: 'none',
  background: 'none',
  color: 'var(--nm-text-muted)',
  cursor: 'pointer',
  font: 'inherit',
  fontSize: '0.85rem',
  textDecoration: 'underline',
} as const;

/** Accepts "1500", "1,500", "1.5e3", "0.75", "75%" (as 75). */
export function parseNumber(raw: string): number | null {
  const cleaned = raw.trim().replace(/,/g, '').replace(/%$/, '');
  if (!/^[-+]?(\d+\.?\d*|\.\d+)(e[-+]?\d+)?$/i.test(cleaned)) return null;
  const value = Number(cleaned);
  return Number.isFinite(value) ? value : null;
}

export function withinTolerance(value: number, answer: number, tolerance: number): boolean {
  if (answer === 0) return Math.abs(value) <= tolerance;
  return Math.abs(value - answer) <= Math.abs(answer) * tolerance;
}

export function Calc({ id, q, answer, unit, tolerance = 0.02, children }: { id: string; q: string; answer: number; unit?: string; tolerance?: number; children: ReactNode }) {
  useRegister(id);
  const [raw, setRaw] = useState('');
  const [result, setResult] = useState<'right' | 'wrong' | 'unparsed' | null>(null);
  const [revealed, setRevealed] = useState(false);
  const solved = result === 'right';

  function check() {
    const value = parseNumber(raw);
    if (value === null) {
      setResult('unparsed');
      return;
    }
    const correct = withinTolerance(value, answer, tolerance);
    setResult(correct ? 'right' : 'wrong');
    record(id, correct);
  }

  return (
    <div style={boxStyle} data-check-id={id}>
      <p style={{ margin: '0 0 0.75rem', fontWeight: 600, color: 'var(--nm-text-primary)' }}>
        <Inline text={q} />
      </p>
      <form
        onSubmit={(e) => {
          e.preventDefault();
          check();
        }}
        style={{ display: 'flex', gap: '0.5rem', alignItems: 'center', flexWrap: 'wrap' }}
      >
        <input
          value={raw}
          onChange={(e) => setRaw(e.target.value)}
          disabled={solved}
          inputMode="decimal"
          aria-label="Your answer"
          style={{ width: 160, padding: '0.45rem 0.6rem', borderRadius: 8, border: '1.5px solid var(--nm-border)', background: 'var(--nm-bg)', color: 'var(--nm-text-primary)', font: 'inherit' }}
        />
        {unit && <span style={{ color: 'var(--nm-text-muted)' }}>{unit}</span>}
        {!solved && (
          <button type="submit" className="nm-button nm-button-secondary" style={{ padding: '0.4rem 0.9rem', fontSize: '0.9rem' }}>
            Check
          </button>
        )}
      </form>
      {result === 'unparsed' && <p style={{ margin: '0.6rem 0 0', color: 'var(--nm-text-muted)' }}>Enter a number, like 0.75 or 1,500.</p>}
      {(result === 'right' || result === 'wrong') && (
        <Verdict correct={solved} text={solved ? `${answer.toLocaleString('en-US', { maximumFractionDigits: 6 })}${unit ? ' ' + unit : ''}.` : 'Check the working and try again.'} />
      )}
      {!solved && !revealed && (
        <button type="button" onClick={() => setRevealed(true)} style={linkButton}>
          Show the answer
        </button>
      )}
      {(solved || revealed) && <Worked>{children}</Worked>}
    </div>
  );
}

/** "You got 12 of 25 right first time" for the questions on this page. */
export function BankScore() {
  const [counts, setCounts] = useState({ total: 0, tried: 0, firstTry: 0 });

  useEffect(() => {
    function recount() {
      const all = readAll();
      const ids = [...registered];
      setCounts({
        total: ids.length,
        tried: ids.filter((id) => all[id]).length,
        firstTry: ids.filter((id) => all[id]?.firstTry).length,
      });
    }
    recount();
    window.addEventListener(EVENT, recount);
    return () => window.removeEventListener(EVENT, recount);
  }, []);

  if (counts.total === 0) return null;
  return (
    <p style={{ fontSize: '0.92rem', color: 'var(--nm-text-muted)' }}>
      {counts.tried === 0
        ? `${counts.total} questions. Each one is checked when you answer, and the worked answer opens after.`
        : `You've answered ${counts.tried} of ${counts.total}, ${counts.firstTry} right on the first try. Saved in this browser only.`}
    </p>
  );
}
