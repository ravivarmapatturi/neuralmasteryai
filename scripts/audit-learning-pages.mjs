import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, relative, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..');
const root = resolve(repoRoot, 'src/content/docs');
const files = [];
function walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) walk(path);
    else if (entry.name.endsWith('.mdx') && !path.includes('/practice-problems/')) files.push(path);
  }
}
walk(root);
const count = (s, pattern) => [...s.matchAll(pattern)].length;
const contains = (s, pattern) => pattern.test(s);
const rows = files.sort().map((file) => {
  const raw = readFileSync(file, 'utf8');
  const body = raw.replace(/^---\s*\n[\s\S]*?\n---\s*\n/, '');
  const path = relative(root, file).replace(/\.mdx$/, '');
  const section = path.split('/')[0];
  const title = raw.match(/^title:\s*['"]?(.+?)['"]?\s*$/m)?.[1] ?? path.split('/').at(-1).replaceAll('-', ' ');
  const words = (body.match(/\b[\p{L}\p{N}]+\b/gu) ?? []).length;
  const h2 = count(body, /^## /gm), h3 = count(body, /^### /gm);
  const images = count(body, /!\[[^\]]*\]\([^)]*\)/g);
  const diagrams = count(body, /<(?:[A-Z][\w]*Diagram|Mermaid|Figure)\b/g);
  const interactives = count(body, /<(?:[A-Z][\w]*(?:Demo|Explorer|Visualizer|Simulator|Playground))\b/g);
  const code = count(body, /^```/gm) / 2;
  const equations = count(body, /\$\$/g) / 2;
  const practice = count(body, /\]\(\/practice\//g);
  const prereq = contains(body, /prerequisite|recommended first/i);
  const objectives = contains(body, /learning objectives|what you.ll learn/i);
  const summary = contains(body, /^## (?:summary|key takeaways|recap)/im);
  const blog = contains(body, /\]\(\/blog\//);
  // Source-only indicators, not a judgment of correctness or pedagogy.
  const score = [Math.min(5, Math.floor(words / 350)), Math.min(5, h2), Math.min(5, diagrams + images), Math.min(5, interactives * 2), Math.min(5, code), Math.min(5, practice * 2), Math.min(5, 2 + Number(prereq) + Number(blog) + Number(summary)), Math.min(5, Number(words > 300) + Number(h2 > 2) + Number(h3 > 0) + Number(summary) + Number(objectives))].reduce((a,b)=>a+b,0);
  return { route: `/docs/${path}`, title, section, module: path.split('/').slice(0,-1).join('/') || section, words, h2, h3, images, diagrams, interactives, code, equations, practice, prereq, objectives, summary, next: true, blog, score, status: score >= 32 ? 'strong' : score >= 24 ? 'acceptable' : score >= 16 ? 'weak' : 'critical' };
});
const columns = ['route','title','section','module','words','h2','h3','images','diagrams','interactives','code','equations','practice','prereq','objectives','summary','next','blog','score','status'];
const clean = value => String(value).replaceAll('|', '\\|').replaceAll('\n',' ');
const table = `| ${columns.join(' | ')} |\n| ${columns.map(()=> '---').join(' | ')} |\n` + rows.map(row=>`| ${columns.map(key=>clean(row[key])).join(' | ')} |`).join('\n');
const totals = Object.fromEntries(['strong','acceptable','weak','critical'].map(status=>[status, rows.filter(row=>row.status===status).length]));
mkdirSync(resolve(repoRoot, 'docs'), { recursive: true });
writeFileSync(resolve(repoRoot, 'docs/learning-page-inventory.md'), `# Learn page source inventory\n\nGenerated by \`node scripts/audit-learning-pages.mjs\`. ${rows.length} MDX files outside practice problems. Counts are source heuristics; shared layout provides previous/next for ordered pages. The score is a triage proxy, not a correctness grade.\n\nStatus counts: ${JSON.stringify(totals)}.\n\n${table}\n`);
console.log(`${rows.length} Learn pages inventoried: ${JSON.stringify(totals)}`);
