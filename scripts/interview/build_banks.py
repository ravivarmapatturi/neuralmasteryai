"""Generate the checkable interview banks under docs/interview-prep/.

    python3 -I scripts/interview/build_banks.py          # write the MDX pages
    python3 -I scripts/interview/build_banks.py --check  # validate only

Each bank module holds sections of questions (see bankkit.py). This script
checks every question (unique ids, a valid answer, a reason on every
option, finite computed answers, text that is safe inside MDX), shuffles
each question's options with a seed taken from its id (so the right answer
isn't always first and the order never changes between builds), and writes
one page per bank. Numeric answers are computed in the bank files, never
typed in by hand.
"""
import json
import math
import os
import random
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT_DIR = os.path.join(ROOT, "src", "content", "docs", "interview-prep")

import bank_classical_ml  # noqa: E402
import bank_dl_training  # noqa: E402
import bank_serving_finetuning  # noqa: E402

BANKS = [
    ("classical-ml-questions", bank_classical_ml),
    ("deep-learning-training-questions", bank_dl_training),
    ("llm-serving-and-fine-tuning-questions", bank_serving_finetuning),
]


def unsafe_for_mdx(text):
    """Braces and angle brackets outside `code` spans would be parsed as JSX."""
    outside_code = re.sub(r"`[^`]*`", "", text)
    return re.findall(r"[{}<]", outside_code)


def validate(slug, bank, seen):
    errors = []
    for section in bank.SECTIONS:
        for q in section["questions"]:
            where = f"{slug}/{q['id']}"
            if q["id"] in seen:
                errors.append(f"{where}: duplicate id")
            seen.add(q["id"])
            # Question and option text go into JS string props (safe). The worked
            # answer and follow-ups become markdown, where braces and < are JSX.
            texts = [q["worked"]] + [t for pair in q["follow"] for t in pair]
            if q["kind"] == "choice":
                if len(q["options"]) < 3:
                    errors.append(f"{where}: fewer than 3 options")
                if not 0 <= q["answer"] < len(q["options"]):
                    errors.append(f"{where}: answer index out of range")
                for o in q["options"]:
                    if not o["why"].strip():
                        errors.append(f"{where}: an option has no reason")
            else:
                if not isinstance(q["answer"], (int, float)) or not math.isfinite(q["answer"]):
                    errors.append(f"{where}: answer isn't a finite number")
                if q["tol"] < 0:
                    errors.append(f"{where}: negative tolerance")
            for t in texts:
                bad = unsafe_for_mdx(t)
                if bad:
                    errors.append(f"{where}: {''.join(bad)} outside code in: {t[:60]}")
            if not q["follow"]:
                errors.append(f"{where}: no follow-up questions")
    return errors


def shuffled(q):
    order = list(range(len(q["options"])))
    random.Random(q["id"]).shuffle(order)
    return [q["options"][i] for i in order], order.index(q["answer"])


def worked_block(q):
    lines = [q["worked"].strip(), "", "**Follow-ups you'll get**", ""]
    lines += [f"- **{a}** {b}" for a, b in q["follow"]]
    return "\n".join(lines)


def render_question(q):
    js = lambda v: json.dumps(v, ensure_ascii=False)  # noqa: E731
    if q["kind"] == "choice":
        options, answer = shuffled(q)
        head = f'<Choice id={js(q["id"])} q={js(q["q"])} answer={{{answer}}} options={{{js(options)}}}>'
        tail = "</Choice>"
    else:
        unit = f' unit={js(q["unit"])}' if q["unit"] else ""
        head = f'<Calc id={js(q["id"])} q={js(q["q"])} answer={{{q["answer"]!r}}} tolerance={{{q["tol"]!r}}}{unit}>'
        tail = "</Calc>"
    return f"{head}\n\n{worked_block(q)}\n\n{tail}"


def render_page(bank):
    count = sum(len(s["questions"]) for s in bank.SECTIONS)
    parts = [
        "---",
        f"title: {json.dumps(bank.TITLE)}",
        f"sidebar_position: {bank.POSITION}",
        f"description: {json.dumps(bank.DESCRIPTION)}",
        "---",
        "",
        "{/* Generated by scripts/interview/build_banks.py from scripts/interview/bank_*.py. Edit those, not this file. */}",
        "",
        "import { Choice, Calc, BankScore } from '../../../components/content/InterviewCheck';",
        "",
        f"# {bank.TITLE}",
        "",
        bank.INTRO.strip(),
        "",
        "<BankScore />",
        "",
    ]
    for section in bank.SECTIONS:
        parts += [f"## {section['title']}", ""]
        if section["intro"]:
            parts += [section["intro"].strip(), ""]
        for q in section["questions"]:
            parts += [render_question(q), ""]
    return "\n".join(parts).rstrip() + "\n", count


def main():
    check_only = "--check" in sys.argv
    seen, errors, answer_slots = set(), [], [0, 0, 0, 0]
    for slug, bank in BANKS:
        errors += validate(slug, bank, seen)
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    total = 0
    for slug, bank in BANKS:
        page, count = render_page(bank)
        total += count
        for section in bank.SECTIONS:
            for q in section["questions"]:
                if q["kind"] == "choice":
                    answer_slots[shuffled(q)[1]] += 1
        calcs = sum(q["kind"] == "calc" for s in bank.SECTIONS for q in s["questions"])
        print(f"  {slug:<42} {count:>2} questions ({calcs} numeric)")
        if not check_only:
            with open(os.path.join(OUT_DIR, slug + ".mdx"), "w") as f:
                f.write(page)
    print(f"{total} questions; right answer lands in option slots 1-4: {answer_slots}")
    print("check OK" if check_only else f"wrote {len(BANKS)} pages to {os.path.relpath(OUT_DIR, ROOT)}")


if __name__ == "__main__":
    main()
